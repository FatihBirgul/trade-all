"""Generate actual schema and explicitly synthetic examples; no live provider I/O."""
from pathlib import Path
import json,sys
ROOT=Path(__file__).resolve().parents[1];sys.path[:0]=[str(ROOT),str(ROOT/'tests')]
from fixtures import fixture,NOW
from unified_forex.api import app
from unified_forex.engine import AnalysisEngine,code_digest
from unified_forex import __version__
PREFIX='V'+__version__.split('.')[0]

schema=app.openapi()
(ROOT/f'docs/{PREFIX}_OPENAPI.json').write_text(json.dumps(schema,indent=2)+'\n',encoding='utf-8')
examples={}
for side in ('BUY','SELL'):
    examples[side]=AnalysisEngine().analyze(fixture(side),'XAUUSD',now=NOW,balance=10000).model_dump(mode='json')
p=fixture();p.data['XAUUSD']['metadata']['broker_hours_verified']=False
examples['UNKNOWN_SESSION']=AnalysisEngine().analyze(p,'XAUUSD',now=NOW,balance=10000).model_dump(mode='json')
(ROOT/f'docs/{PREFIX}_RESPONSE_EXAMPLES.json').write_text(json.dumps({'data_kind':'SYNTHETIC_TEST','market_validation':False,'code_sha256':code_digest(),'examples':examples},indent=2)+'\n',encoding='utf-8')
paths=sorted(schema['paths'])
(ROOT/f'docs/{PREFIX}_ROUTES.md').write_text('# Generated actual route inventory\n\n'+f'{len(paths)} unique paths. Generated by scripts/export_contract.py.\n\n'+
    '\n'.join(f"- {','.join(k.upper() for k in schema['paths'][path] if k in ('get','post','put','delete','patch'))} `{path}`" for path in paths)+'\n',encoding='utf-8')
print({'paths':len(paths),'legacy':sum('/api/v6/' not in p for p in paths),'v6':sum('/api/v6/' in p for p in paths)})
